export type TrackStoreWarning =
  /** No IndexedDB at all (Safari private mode, some embedded webviews). */
  | "no_indexeddb"
  /** IndexedDB exists but `open()` failed, was blocked, or the DB was evicted
   *  and re-created empty. */
  | "indexeddb_failed";

export interface TrackStoreOptions {
  /** Inject a storage adapter — tests use `MemoryTrackStorage` directly. */
  storage?: TrackStorage;
  /** Defaults to `globalThis.indexedDB`; pass null to force the fallback. */
  indexedDBFactory?: IDBFactory | null;
  now?: () => number;
  randomBytes?: (n: number) => Bytes;
  /** Private/guest rides normally use `crypto.subtle.generateKey`; tests
   *  inject a deterministic key instead. */
  generatePrivateKey?: () => Promise<CryptoKey>;
}

export interface TrackResumeOptions {
  /** `active.track_signing` — lets a resume re-import the key after the local
   *  record was evicted. */
  signing?: TrackSigning | null;
  /** Resume a private ride, which has no server signing material to fall back
   *  on: an evicted record means a new chain under a new client-random key. */
  isPrivate?: boolean;
}

export interface TrackResume {
  recorder: TrackRecorder;
  /** True when sealed batches survived locally and the recorder continues that
   *  chain from its tip. */
  continued: boolean;
  /** True when nothing survived and recording restarts at `seq 0` / `prev: ""`.
   *  The recovery table's honest path: never pretend the pre-eviction track is
   *  intact — donate what survives and let server validation adjudicate. */
  freshChain: boolean;
  keySource: "idb" | "server" | "generated";
  /** The `rec:true` batch sealed from crash-recovered unsealed points. */
  recovered: StoredTrackBatch | null;
  tip: TrackTip;
}

export interface TrackStore {
  readonly durable: boolean;
  readonly warning: TrackStoreWarning | null;
  readonly storage: TrackStorage;
  startServerRide(signing: TrackSigning): Promise<TrackRecorder>;
  startPrivateRide(): Promise<TrackRecorder>;
  resumeRide(trackId: string, opts?: TrackResumeOptions): Promise<TrackResume>;
  /** The chain tip as the recovery table needs it, derived from the `batches`
   *  store (authoritative) — null when this device knows nothing about the
   *  ride. */
  readTip(trackId: string): Promise<TrackTip | null>;
  listTrackIds(): Promise<string[]>;
  deleteRide(trackId: string): Promise<void>;
}

const DEFAULT_RANDOM_BYTES = (n: number): Bytes =>
  crypto.getRandomValues(new Uint8Array(n));

class TrackStoreImpl implements TrackStore {
  readonly storage: TrackStorage;
  readonly warning: TrackStoreWarning | null;
  private readonly now: () => number;
  private readonly randomBytes: (n: number) => Bytes;
  private readonly generatePrivateKey: () => Promise<CryptoKey>;

  constructor(
    storage: TrackStorage,
    warning: TrackStoreWarning | null,
    opts: TrackStoreOptions,
  ) {
    this.storage = storage;
    this.warning = warning;
    this.now = opts.now ?? (() => Date.now());
    this.randomBytes = opts.randomBytes ?? DEFAULT_RANDOM_BYTES;
    this.generatePrivateKey = opts.generatePrivateKey ?? generateTrackKey;
  }

  get durable(): boolean {
    return this.storage.durable;
  }

  async startServerRide(signing: TrackSigning): Promise<TrackRecorder> {
    const rideId = signing.key_id;
    const ride: StoredTrackRide = {
      trackId: rideId,
      rideId,
      private: false,
      nonce: signing.nonce,
      rid: rideId,
      kid: rideId,
      key: await importTrackKey(signing.key),
      createdAtMs: this.now(),
      nextSeq: 0,
      prevJwsHash: "",
      chainHash: bytesToHex(await initialChainHash(signing.nonce)),
      batchCount: 0,
      waypointCount: 0,
      lastPointMs: null,
    };
    return this.begin(ride);
  }

  async startPrivateRide(): Promise<TrackRecorder> {
    const nonce = bytesToHex(this.randomBytes(16));
    const ride: StoredTrackRide = {
      trackId: `${PRIVATE_RIDE_ID}-${bytesToHex(this.randomBytes(6))}`,
      rideId: null,
      private: true,
      nonce,
      // No tracked_rides row exists, so the payload's ride identity is the
      // literal "private" (master Part 2) and the header's kid matches it.
      // Local records are told apart by `trackId`, not by kid.
      rid: PRIVATE_RIDE_ID,
      kid: PRIVATE_RIDE_ID,
      key: await this.generatePrivateKey(),
      createdAtMs: this.now(),
      nextSeq: 0,
      prevJwsHash: "",
      chainHash: bytesToHex(await initialChainHash(nonce)),
      batchCount: 0,
      waypointCount: 0,
      lastPointMs: null,
    };
    return this.begin(ride);
  }

  private async begin(ride: StoredTrackRide): Promise<TrackRecorder> {
    await this.storage.putRide(ride);
    await this.storage.deletePending(ride.trackId);
    return new TrackRecorder({
      storage: this.storage,
      ride,
      tip: {
        trackId: ride.trackId,
        nextSeq: 0,
        prevJwsHash: "",
        chainHash: ride.chainHash,
        batchCount: 0,
        waypointCount: 0,
        pendingCount: 0,
        lastPointMs: null,
      },
      open: null,
      chainHash: hexToBytes(ride.chainHash),
    });
  }

  async readTip(trackId: string): Promise<TrackTip | null> {
    const [ride, batches, pending] = await Promise.all([
      this.storage.getRide(trackId),
      this.storage.getBatches(trackId),
      this.storage.getPending(trackId),
    ]);
    if (!ride && batches.length === 0) return null;
    return tipFromBatches(trackId, batches, ride, pending);
  }

  async resumeRide(
    trackId: string,
    opts: TrackResumeOptions = {},
  ): Promise<TrackResume> {
    const stored = await this.storage.getRide(trackId);
    const batches = await this.storage.getBatches(trackId);
    const signing = opts.signing ?? null;

    let ride: StoredTrackRide | null = stored;
    let keySource: TrackResume["keySource"] = "idb";
    if (!ride) {
      // The local record is gone. Two honest outcomes, and neither pretends
      // the pre-eviction chain survived: re-import the server key (a server
      // ride) or mint a new client-random one (a private ride).
      if (signing) {
        keySource = "server";
        ride = {
          trackId,
          rideId: signing.key_id,
          private: false,
          nonce: signing.nonce,
          rid: signing.key_id,
          kid: signing.key_id,
          key: await importTrackKey(signing.key),
          createdAtMs: this.now(),
          nextSeq: 0,
          prevJwsHash: "",
          chainHash: bytesToHex(await initialChainHash(signing.nonce)),
          batchCount: 0,
          waypointCount: 0,
          lastPointMs: null,
        };
      } else if (opts.isPrivate) {
        keySource = "generated";
        const nonce = bytesToHex(this.randomBytes(16));
        ride = {
          trackId,
          rideId: null,
          private: true,
          nonce,
          rid: PRIVATE_RIDE_ID,
          kid: PRIVATE_RIDE_ID,
          key: await this.generatePrivateKey(),
          createdAtMs: this.now(),
          nextSeq: 0,
          prevJwsHash: "",
          chainHash: bytesToHex(await initialChainHash(nonce)),
          batchCount: 0,
          waypointCount: 0,
          lastPointMs: null,
        };
      } else {
        throw new TrackStoreError(
          "missing_signing",
          `no local track for ${trackId} and no track_signing to re-import`,
        );
      }
      await this.storage.putRide(ride);
    }

    // Batches only continue a chain when they were signed under the SAME
    // nonce; a re-imported key with a rotated nonce is a different chain.
    const stale =
      batches.length > 0 && !batchesMatchNonce(batches, ride.nonce);
    const usable = stale ? [] : batches;
    if (stale) {
      // Wipe the old generation outright. Splicing two chains together is
      // obviously wrong, but so is leaving it in place: the new chain restarts
      // at seq 0 and would only overwrite the old batches it collides with,
      // leaving higher-seq orphans for a later donation to upload.
      await this.storage.deleteRide(trackId);
      await this.storage.putRide(ride);
    }
    const tip = tipFromBatches(trackId, usable, ride, null);
    const recorder = new TrackRecorder({
      storage: this.storage,
      ride: { ...ride, ...tipFields(tip) },
      tip,
      open: null,
      chainHash: hexToBytes(tip.chainHash),
    });

    // Crash mid-batch: replay the `pending` store and seal it as `rec:true`.
    let recovered: StoredTrackBatch | null = null;
    const pending = stale ? null : await this.storage.getPending(trackId);
    if (pending && pending.points.length > 0) {
      const startsAfterTip =
        tip.lastPointMs === null || pending.t0 > tip.lastPointMs;
      if (startsAfterTip) {
        recovered = await recorder.adoptPending(pending);
      } else {
        // Points that predate the sealed tip would break check 3's strict
        // monotonicity — they are a stale write, not recoverable data.
        await this.storage.deletePending(trackId);
      }
    }

    return {
      recorder,
      continued: usable.length > 0,
      freshChain: usable.length === 0,
      keySource,
      recovered,
      tip: recovered ? recorder.info() : tip,
    };
  }

  async listTrackIds(): Promise<string[]> {
    const rides = await this.storage.listRides();
    return rides.map((r) => r.trackId);
  }

  deleteRide(trackId: string): Promise<void> {
    return this.storage.deleteRide(trackId);
  }
}

function tipFields(tip: TrackTip): Pick<
  StoredTrackRide,
  "nextSeq" | "prevJwsHash" | "chainHash" | "batchCount" | "waypointCount" | "lastPointMs"
> {
  return {
    nextSeq: tip.nextSeq,
    prevJwsHash: tip.prevJwsHash,
    chainHash: tip.chainHash,
    batchCount: tip.batchCount,
    waypointCount: tip.waypointCount,
    lastPointMs: tip.lastPointMs,
  };
}

function batchesMatchNonce(
  batches: readonly StoredTrackBatch[],
  nonce: string,
): boolean {
  try {
    return decodeTrackBatch(batches[0].jws).non === nonce;
  } catch {
    return false;
  }
}

/** Derive the chain tip from the sealed batches — the store that gets
 *  uploaded, and therefore the authority. The ride record's mirrored tip is
 *  only used to answer "what is H_-1" when nothing is sealed yet. */
function tipFromBatches(
  trackId: string,
  batches: readonly StoredTrackBatch[],
  ride: StoredTrackRide | null,
  pending: StoredPendingBatch | null,
): TrackTip {
  if (batches.length === 0) {
    return {
      trackId,
      nextSeq: 0,
      prevJwsHash: "",
      chainHash: ride?.chainHash ?? "",
      batchCount: 0,
      waypointCount: 0,
      pendingCount: pending?.points.length ?? 0,
      lastPointMs: pending?.lastPointMs ?? null,
    };
  }
  const last = batches[batches.length - 1];
  return {
    trackId,
    nextSeq: last.seq + 1,
    prevJwsHash: last.jwsHash,
    chainHash: last.chainHash,
    batchCount: batches.length,
    waypointCount: batches.reduce((n, b) => n + b.count, 0),
    pendingCount: pending?.points.length ?? 0,
    lastPointMs: pending ? Math.max(last.t1, pending.lastPointMs) : last.t1,
  };
}

/** Open the local track store. Never throws for a missing or hostile
 *  IndexedDB: it degrades to memory and reports it through `durable` /
 *  `warning` so the UI can show `TRACK_FALLBACK_WARNING`. */
export async function openTrackStore(
  opts: TrackStoreOptions = {},
): Promise<TrackStore> {
  if (opts.storage) {
    // Keep the UI invariant honest: `durable === false` always comes with a
    // warning, even for an injected adapter.
    return new TrackStoreImpl(
      opts.storage,
      opts.storage.durable ? null : "no_indexeddb",
      opts,
    );
  }
  const factory =
    opts.indexedDBFactory !== undefined
      ? opts.indexedDBFactory
      : ((globalThis as { indexedDB?: IDBFactory }).indexedDB ?? null);
  if (!factory) {
    return new TrackStoreImpl(new MemoryTrackStorage(), "no_indexeddb", opts);
  }
  try {
    const storage = await IdbTrackStorage.open(factory);
    return new TrackStoreImpl(storage, null, opts);
  } catch {
    return new TrackStoreImpl(
      new MemoryTrackStorage(),
      "indexeddb_failed",
      opts,
    );
  }
}
