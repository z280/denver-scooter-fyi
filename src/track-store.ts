// ---------------------------------------------------------------------------
// Storage adapter. Two implementations: IndexedDB (`sfyi-tracks`) and an
// in-memory fallback for private mode / no-IDB browsers. The interface exists
// so the recorder is unit-testable without a fake IDB, and so the eviction
// paths recovery has to handle can be provoked deterministically.
// ---------------------------------------------------------------------------

export interface StoredTrackRide {
  /** Primary key. Equals the `rideId` for a server ride (so the recovery
   *  table's "batches store keyed by rideId" reads literally); a
   *  `private-<hex>` local id for a private ride. */
  trackId: string;
  rideId: string | null;
  private: boolean;
  /** Hex, 16 bytes. */
  nonce: string;
  /** Payload `rid` — the ride id, or `PRIVATE_RIDE_ID`. */
  rid: string;
  /** Protected-header `kid` — the same value as `rid`. */
  kid: string;
  key: CryptoKey;
  createdAtMs: number;
  // ----- chain tip, mirrored here so a resume is O(1). The `batches` store
  // stays authoritative: it is what gets uploaded, so `readTip` derives from
  // it and this mirror is only a cross-check.
  nextSeq: number;
  prevJwsHash: string;
  chainHash: string;
  batchCount: number;
  waypointCount: number;
  lastPointMs: number | null;
}

export interface StoredTrackBatch {
  trackId: string;
  seq: number;
  /** The compact JWS — the only thing donation uploads. */
  jws: string;
  /** Lowercase hex `sha256(jws)`; the successor's `prev`. */
  jwsHash: string;
  /** Lowercase hex `H_n` after this batch. */
  chainHash: string;
  t0: number;
  t1: number;
  count: number;
  rec: boolean;
}

export interface StoredPendingBatch {
  trackId: string;
  t0: number;
  points: WaypointTuple[];
  lastPointMs: number;
}

export interface TrackStorage {
  /** False for the in-memory fallback — the UI's warning flag. */
  readonly durable: boolean;
  putRide(ride: StoredTrackRide): Promise<void>;
  getRide(trackId: string): Promise<StoredTrackRide | null>;
  listRides(): Promise<StoredTrackRide[]>;
  getBatches(trackId: string): Promise<StoredTrackBatch[]>;
  /** Atomic seal: append the batch, advance the ride's chain tip and drop the
   *  pending open batch in ONE transaction. Doing these as three writes would
   *  let a crash in the middle replay already-sealed points as a `rec:true`
   *  batch and double-count them. */
  commitSeal(batch: StoredTrackBatch, ride: StoredTrackRide): Promise<void>;
  putPending(pending: StoredPendingBatch): Promise<void>;
  getPending(trackId: string): Promise<StoredPendingBatch | null>;
  deletePending(trackId: string): Promise<void>;
  deleteRide(trackId: string): Promise<void>;
}

export class MemoryTrackStorage implements TrackStorage {
  readonly durable = false;
  private readonly rides = new Map<string, StoredTrackRide>();
  private readonly batches = new Map<string, Map<number, StoredTrackBatch>>();
  private readonly pending = new Map<string, StoredPendingBatch>();

  async putRide(ride: StoredTrackRide): Promise<void> {
    this.rides.set(ride.trackId, { ...ride });
  }

  async getRide(trackId: string): Promise<StoredTrackRide | null> {
    const found = this.rides.get(trackId);
    return found ? { ...found } : null;
  }

  async listRides(): Promise<StoredTrackRide[]> {
    return [...this.rides.values()].map((r) => ({ ...r }));
  }

  async getBatches(trackId: string): Promise<StoredTrackBatch[]> {
    const bySeq = this.batches.get(trackId);
    if (!bySeq) return [];
    return [...bySeq.values()]
      .map((b) => ({ ...b }))
      .sort((a, b) => a.seq - b.seq);
  }

  async commitSeal(
    batch: StoredTrackBatch,
    ride: StoredTrackRide,
  ): Promise<void> {
    let bySeq = this.batches.get(batch.trackId);
    if (!bySeq) {
      bySeq = new Map();
      this.batches.set(batch.trackId, bySeq);
    }
    bySeq.set(batch.seq, { ...batch });
    this.rides.set(ride.trackId, { ...ride });
    this.pending.delete(batch.trackId);
  }

  async putPending(pending: StoredPendingBatch): Promise<void> {
    this.pending.set(pending.trackId, {
      ...pending,
      points: pending.points.map((p) => [...p] as WaypointTuple),
    });
  }

  async getPending(trackId: string): Promise<StoredPendingBatch | null> {
    const found = this.pending.get(trackId);
    return found
      ? { ...found, points: found.points.map((p) => [...p] as WaypointTuple) }
      : null;
  }

  async deletePending(trackId: string): Promise<void> {
    this.pending.delete(trackId);
  }

  async deleteRide(trackId: string): Promise<void> {
    this.rides.delete(trackId);
    this.batches.delete(trackId);
    this.pending.delete(trackId);
  }
}

function idbRequest<T>(request: IDBRequest<T>): Promise<T> {
  return new Promise<T>((resolve, reject) => {
    request.onsuccess = () => resolve(request.result);
    request.onerror = () =>
      reject(
        new TrackStoreError(
          "storage",
          request.error?.message ?? "IndexedDB request failed",
        ),
      );
  });
}

function idbTxDone(tx: IDBTransaction): Promise<void> {
  return new Promise<void>((resolve, reject) => {
    tx.oncomplete = () => resolve();
    tx.onabort = tx.onerror = () =>
      reject(
        new TrackStoreError(
          "storage",
          tx.error?.message ?? "IndexedDB transaction aborted",
        ),
      );
  });
}

export class IdbTrackStorage implements TrackStorage {
  readonly durable = true;
  private readonly db: IDBDatabase;

  constructor(db: IDBDatabase) {
    this.db = db;
  }

  static open(factory: IDBFactory): Promise<IdbTrackStorage> {
    return new Promise<IdbTrackStorage>((resolve, reject) => {
      const request = factory.open(TRACK_DB_NAME, TRACK_DB_VERSION);
      request.onupgradeneeded = () => {
        const db = request.result;
        if (!db.objectStoreNames.contains(TRACK_STORE_RIDES)) {
          db.createObjectStore(TRACK_STORE_RIDES, { keyPath: "trackId" });
        }
        if (!db.objectStoreNames.contains(TRACK_STORE_BATCHES)) {
          const batches = db.createObjectStore(TRACK_STORE_BATCHES, {
            keyPath: ["trackId", "seq"],
          });
          batches.createIndex("trackId", "trackId", { unique: false });
        }
        if (!db.objectStoreNames.contains(TRACK_STORE_PENDING)) {
          db.createObjectStore(TRACK_STORE_PENDING, { keyPath: "trackId" });
        }
      };
      request.onsuccess = () => resolve(new IdbTrackStorage(request.result));
      request.onerror = () =>
        reject(
          new TrackStoreError(
            "storage",
            request.error?.message ?? "could not open IndexedDB",
          ),
        );
      request.onblocked = () =>
        reject(new TrackStoreError("storage", "IndexedDB open blocked"));
    });
  }

  private async write(
    stores: string[],
    body: (tx: IDBTransaction) => void,
  ): Promise<void> {
    const tx = this.db.transaction(stores, "readwrite");
    const done = idbTxDone(tx);
    body(tx);
    await done;
  }

  async putRide(ride: StoredTrackRide): Promise<void> {
    await this.write([TRACK_STORE_RIDES], (tx) => {
      tx.objectStore(TRACK_STORE_RIDES).put(ride);
    });
  }

  async getRide(trackId: string): Promise<StoredTrackRide | null> {
    const tx = this.db.transaction([TRACK_STORE_RIDES], "readonly");
    const row = await idbRequest<StoredTrackRide | undefined>(
      tx.objectStore(TRACK_STORE_RIDES).get(trackId),
    );
    return row ?? null;
  }

  async listRides(): Promise<StoredTrackRide[]> {
    const tx = this.db.transaction([TRACK_STORE_RIDES], "readonly");
    return idbRequest<StoredTrackRide[]>(
      tx.objectStore(TRACK_STORE_RIDES).getAll(),
    );
  }

  async getBatches(trackId: string): Promise<StoredTrackBatch[]> {
    const tx = this.db.transaction([TRACK_STORE_BATCHES], "readonly");
    const rows = await idbRequest<StoredTrackBatch[]>(
      tx.objectStore(TRACK_STORE_BATCHES).index("trackId").getAll(trackId),
    );
    return rows.sort((a, b) => a.seq - b.seq);
  }

  async commitSeal(
    batch: StoredTrackBatch,
    ride: StoredTrackRide,
  ): Promise<void> {
    await this.write(
      [TRACK_STORE_BATCHES, TRACK_STORE_RIDES, TRACK_STORE_PENDING],
      (tx) => {
        tx.objectStore(TRACK_STORE_BATCHES).put(batch);
        tx.objectStore(TRACK_STORE_RIDES).put(ride);
        tx.objectStore(TRACK_STORE_PENDING).delete(batch.trackId);
      },
    );
  }

  async putPending(pending: StoredPendingBatch): Promise<void> {
    await this.write([TRACK_STORE_PENDING], (tx) => {
      tx.objectStore(TRACK_STORE_PENDING).put(pending);
    });
  }

  async getPending(trackId: string): Promise<StoredPendingBatch | null> {
    const tx = this.db.transaction([TRACK_STORE_PENDING], "readonly");
    const row = await idbRequest<StoredPendingBatch | undefined>(
      tx.objectStore(TRACK_STORE_PENDING).get(trackId),
    );
    return row ?? null;
  }

  async deletePending(trackId: string): Promise<void> {
    await this.write([TRACK_STORE_PENDING], (tx) => {
      tx.objectStore(TRACK_STORE_PENDING).delete(trackId);
    });
  }

  async deleteRide(trackId: string): Promise<void> {
    const batches = await this.getBatches(trackId);
    await this.write(
      [TRACK_STORE_RIDES, TRACK_STORE_BATCHES, TRACK_STORE_PENDING],
      (tx) => {
        tx.objectStore(TRACK_STORE_RIDES).delete(trackId);
        const store = tx.objectStore(TRACK_STORE_BATCHES);
        for (const b of batches) store.delete([trackId, b.seq]);
        tx.objectStore(TRACK_STORE_PENDING).delete(trackId);
      },
    );
  }
}

