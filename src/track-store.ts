/** One GPS fix as the HUD's shared `watchPosition` hands it over. */
export interface TrackFix {
  /** Epoch ms — `GeolocationPosition.timestamp`. */
  tMs: number;
  lat: number;
  lon: number;
  /** `coords.accuracy` in metres. Unknown becomes 0, never a large number:
   *  the server SUBTRACTS accuracy from segment distance before the speed
   *  check, so inflating it would be gaming our own rider's chain. */
  accM?: number | null;
}

export type TrackFixRejection =
  | "not_recording"
  | "non_monotonic"
  | "invalid_fix";

export interface TrackAddResult {
  accepted: boolean;
  rejected: TrackFixRejection | null;
  /** The batch this fix's arrival sealed (the 25-waypoint or 60-second rule). */
  sealed: StoredTrackBatch | null;
  /** Unsealed points held in the `pending` store after this call. */
  openCount: number;
}

export interface TrackFinishResult {
  /** The final partial batch, or null when nothing was open. */
  sealed: StoredTrackBatch | null;
  batchCount: number;
  waypointCount: number;
  chainRootHash: string | null;
}

export interface TrackTip {
  trackId: string;
  /** The seq the NEXT sealed batch will carry. */
  nextSeq: number;
  /** `prev` for the next batch — `""` when nothing is sealed yet. */
  prevJwsHash: string;
  /** Lowercase hex `H_n` of the last sealed batch, or `H_-1` when none. */
  chainHash: string;
  batchCount: number;
  waypointCount: number;
  /** Unsealed points still sitting in the `pending` store. They WILL become a
   *  `rec:true` batch on resume, so "were any waypoints recorded?" is
   *  `waypointCount + pendingCount`, not `waypointCount` alone. */
  pendingCount: number;
  /** `t1` of the last sealed batch (or the newest pending point). */
  lastPointMs: number | null;
}

export interface TrackSessionInfo extends TrackTip {
  rideId: string | null;
  private: boolean;
  nonce: string;
  recording: boolean;
  durable: boolean;
  openCount: number;
  /** Lowercase hex `H_n`, or null before the first seal. */
  chainRootHash: string | null;
}

interface OpenBatch {
  t0: number;
  lastMs: number;
  points: WaypointTuple[];
}

function roundCoord(value: number): number {
  // toFixed then re-parse: the shortest round-tripping double for an exact
  // 6-decimal value, which is what JSON.stringify then emits. Doing the same
  // arithmetic in the fixture generator is why the two agree byte-for-byte.
  return Number(value.toFixed(WAYPOINT_COORD_DECIMALS));
}

function roundAccuracy(accM: number | null | undefined): number {
  if (accM === null || accM === undefined || !Number.isFinite(accM)) return 0;
  return Math.max(0, Math.round(accM));
}

/** Records one ride's track. Serialized internally: every mutating call joins
 *  a promise chain, so a burst of fixes can never interleave two seals and
 *  skip a `seq`. */
export class TrackRecorder {
  readonly trackId: string;
  readonly rideId: string | null;
  readonly isPrivate: boolean;
  readonly nonce: string;

  private readonly storage: TrackStorage;
  private readonly key: CryptoKey;
  private readonly rid: string;
  private readonly kid: string;
  private readonly createdAtMs: number;

  private nextSeq: number;
  private prevJwsHash: string;
  private chainHash: Bytes;
  private batchCount: number;
  private waypointCount: number;
  private lastPointMs: number | null;
  private open: OpenBatch | null = null;
  private recording = true;
  private queue: Promise<unknown> = Promise.resolve();

  constructor(init: {
    storage: TrackStorage;
    ride: StoredTrackRide;
    tip: TrackTip;
    open: OpenBatch | null;
    chainHash: Bytes;
  }) {
    this.storage = init.storage;
    this.trackId = init.ride.trackId;
    this.rideId = init.ride.rideId;
    this.isPrivate = init.ride.private;
    this.nonce = init.ride.nonce;
    this.key = init.ride.key;
    this.rid = init.ride.rid;
    this.kid = init.ride.kid;
    this.createdAtMs = init.ride.createdAtMs;
    this.nextSeq = init.tip.nextSeq;
    this.prevJwsHash = init.tip.prevJwsHash;
    this.chainHash = init.chainHash;
    this.batchCount = init.tip.batchCount;
    this.waypointCount = init.tip.waypointCount;
    this.lastPointMs = init.tip.lastPointMs;
    this.open = init.open;
  }

  get durable(): boolean {
    return this.storage.durable;
  }

  /** Lowercase hex `H_n`, or null before the first seal — what donation
   *  reports as `chain_root_hash`. */
  get chainRootHash(): string | null {
    return this.batchCount > 0 ? bytesToHex(this.chainHash) : null;
  }

  get isRecording(): boolean {
    return this.recording;
  }

  info(): TrackSessionInfo {
    return {
      trackId: this.trackId,
      rideId: this.rideId,
      private: this.isPrivate,
      nonce: this.nonce,
      nextSeq: this.nextSeq,
      prevJwsHash: this.prevJwsHash,
      chainHash: bytesToHex(this.chainHash),
      chainRootHash: this.chainRootHash,
      batchCount: this.batchCount,
      waypointCount: this.waypointCount,
      // The in-memory open batch IS what the `pending` store holds, so these
      // two are the same number by construction.
      pendingCount: this.open?.points.length ?? 0,
      lastPointMs: this.lastPointMs,
      recording: this.recording,
      durable: this.storage.durable,
      openCount: this.open?.points.length ?? 0,
    };
  }

  /** Record one fix. Rejects a non-advancing timestamp rather than writing it:
   *  the API's check 3 requires strictly increasing timestamps across the
   *  flattened track, and a duplicated or back-dated GPS sample would fail the
   *  whole chain. Dropping a duplicate is deduplication, not fabrication. */
  addFix(fix: TrackFix): Promise<TrackAddResult> {
    return this.run(() => this.addFixLocked(fix));
  }

  /** Seal whatever is open. `rec` marks a batch rebuilt from crash-recovered
   *  points. Returns null when nothing was open. */
  sealOpenBatch(opts: { rec?: boolean } = {}): Promise<StoredTrackBatch | null> {
    return this.run(() => this.sealLocked(opts.rec === true));
  }

  /** Ride end (or the wrench's "Stop tracking"): seal the final partial batch
   *  and stop accepting fixes. Idempotent. */
  finish(): Promise<TrackFinishResult> {
    return this.run(async () => {
      // Recording stops even if the final seal's write fails: the ride IS over,
      // and the unsealed points stay in the `pending` store, so a later resume
      // still seals them as a `rec:true` batch. The rejection reaches the caller
      // either way, and calling `finish()` again retries the seal.
      let sealed: StoredTrackBatch | null;
      try {
        sealed = await this.sealLocked(false);
      } finally {
        this.recording = false;
      }
      return {
        sealed,
        batchCount: this.batchCount,
        waypointCount: this.waypointCount,
        chainRootHash: this.chainRootHash,
      };
    });
  }

  /** Crash recovery: adopt unsealed points left in the `pending` store and
   *  seal them immediately as a `rec:true` batch. Called by `resumeRide`
   *  before any new fix is accepted, so the recovered points keep their
   *  original place in the chain. */
  adoptPending(pending: StoredPendingBatch): Promise<StoredTrackBatch | null> {
    return this.run(async () => {
      if (this.open) return null;
      const points = pending.points.map((p) => [...p] as WaypointTuple);
      if (points.length === 0) return null;
      this.open = {
        t0: pending.t0,
        lastMs: pending.lastPointMs,
        points,
      };
      return this.sealLocked(true);
    });
  }

  /** Every sealed batch, seq-ordered — the donation body's `batches`. */
  batches(): Promise<StoredTrackBatch[]> {
    return this.run(() => this.storage.getBatches(this.trackId));
  }

  /** `POST /tracked-rides/{id}/track`'s body. One request, no chunking. */
  async buildDonation(): Promise<DonateTrackIn> {
    if (this.isPrivate) {
      throw new TrackStoreError(
        "private_ride",
        "a private ride's chain is signed with a client-random key and is never donatable",
      );
    }
    const batches = await this.batches();
    const body: DonateTrackIn = { batches: batches.map((b) => b.jws) };
    const root = batches.length ? batches[batches.length - 1].chainHash : null;
    if (root) body.chain_root_hash = root;
    return body;
  }

  /** Wipe this ride's local track. Donation is opt-in; this is the "never
   *  mind" path, and the only way waypoints leave the device is a donation. */
  discard(): Promise<void> {
    return this.run(async () => {
      this.recording = false;
      this.open = null;
      await this.storage.deleteRide(this.trackId);
    });
  }

  // ----- internals

  private run<T>(fn: () => Promise<T>): Promise<T> {
    const next = this.queue.then(fn, fn);
    this.queue = next.then(
      () => undefined,
      () => undefined,
    );
    return next;
  }

  private async addFixLocked(fix: TrackFix): Promise<TrackAddResult> {
    if (!this.recording) {
      return {
        accepted: false,
        rejected: "not_recording",
        sealed: null,
        openCount: this.open?.points.length ?? 0,
      };
    }
    if (
      !Number.isFinite(fix.tMs) ||
      !Number.isFinite(fix.lat) ||
      !Number.isFinite(fix.lon) ||
      Math.abs(fix.lat) > 90 ||
      Math.abs(fix.lon) > 180
    ) {
      return {
        accepted: false,
        rejected: "invalid_fix",
        sealed: null,
        openCount: this.open?.points.length ?? 0,
      };
    }
    const tMs = Math.round(fix.tMs);
    const newest = this.open ? this.open.lastMs : this.lastPointMs;
    if (newest !== null && tMs <= newest) {
      return {
        accepted: false,
        rejected: "non_monotonic",
        sealed: null,
        openCount: this.open?.points.length ?? 0,
      };
    }

    // The 60-second rule: the fix that reaches the bound opens the NEXT batch,
    // so a sealed batch always spans strictly less than MAX_BATCH_SPAN_MS.
    let sealed: StoredTrackBatch | null = null;
    if (this.open && tMs - this.open.t0 >= MAX_BATCH_SPAN_MS) {
      sealed = await this.sealLocked(false);
    }
    if (!this.open) this.open = { t0: tMs, lastMs: tMs, points: [] };

    this.open.points.push([
      tMs - this.open.t0,
      roundCoord(fix.lat),
      roundCoord(fix.lon),
      roundAccuracy(fix.accM),
    ]);
    this.open.lastMs = tMs;
    await this.storage.putPending({
      trackId: this.trackId,
      t0: this.open.t0,
      points: this.open.points,
      lastPointMs: this.open.lastMs,
    });

    // The 25-waypoint rule: a full batch seals immediately, so it never waits
    // on the next fix (which may never come — a ride can end here).
    if (this.open.points.length >= MAX_WAYPOINTS_PER_BATCH) {
      sealed = await this.sealLocked(false);
    }
    return {
      accepted: true,
      rejected: null,
      sealed,
      openCount: this.open?.points.length ?? 0,
    };
  }

  private async sealLocked(rec: boolean): Promise<StoredTrackBatch | null> {
    const open = this.open;
    if (!open || open.points.length === 0) return null;
    const payload: TrackBatchPayload = {
      v: TRACK_PAYLOAD_VERSION,
      rid: this.rid,
      non: this.nonce,
      seq: this.nextSeq,
      prev: this.prevJwsHash,
      t0: open.t0,
      t1: open.lastMs,
      pts: open.points,
      rec,
    };
    const jws = await signTrackBatch(this.key, this.kid, payload);
    const jwsDigest = await sha256(asciiBytes(jws));
    const chainHash = await sha256(concatBytes(this.chainHash, jwsDigest));
    const batch: StoredTrackBatch = {
      trackId: this.trackId,
      seq: this.nextSeq,
      jws,
      jwsHash: bytesToHex(jwsDigest),
      chainHash: bytesToHex(chainHash),
      t0: payload.t0,
      t1: payload.t1,
      count: open.points.length,
      rec,
    };

    // The ride row committed alongside the batch describes the POST-seal tip
    // (one atomic write), but the recorder's own tip only moves once that write
    // has landed. Advancing first would make a single transient IndexedDB
    // failure permanent and silent: seq would already have skipped past a batch
    // that never reached the store, so the donated chain would be
    // non-contiguous and fail the API's check 2 as `chain_invalid` — with the
    // rider's points lost for a write they never saw fail. Leaving the batch
    // open instead means the next fix (or `finish()`) simply re-seals it.
    const post = this.tipAfter(batch, chainHash);
    await this.storage.commitSeal(batch, post);
    this.nextSeq = post.nextSeq;
    this.prevJwsHash = post.prevJwsHash;
    this.chainHash = chainHash;
    this.batchCount = post.batchCount;
    this.waypointCount = post.waypointCount;
    this.lastPointMs = post.lastPointMs;
    this.open = null;
    return batch;
  }

  /** The ride record as it will read once `batch` is sealed. Pure — it reads
   *  `this` but mutates nothing, which is what lets the commit happen before
   *  the recorder moves. */
  private tipAfter(batch: StoredTrackBatch, chainHash: Bytes): StoredTrackRide {
    return {
      trackId: this.trackId,
      rideId: this.rideId,
      private: this.isPrivate,
      nonce: this.nonce,
      rid: this.rid,
      kid: this.kid,
      key: this.key,
      createdAtMs: this.createdAtMs,
      nextSeq: batch.seq + 1,
      prevJwsHash: batch.jwsHash,
      chainHash: bytesToHex(chainHash),
      batchCount: this.batchCount + 1,
      waypointCount: this.waypointCount + batch.count,
      lastPointMs: batch.t1,
    };
  }
}

