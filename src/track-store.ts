// ---------------------------------------------------------------------------
// Byte plumbing. Hand-rolled base64url rather than btoa/atob so the encoding
// is identical in a browser, in `node` and under happy-dom, with no reliance
// on a legacy global.
// ---------------------------------------------------------------------------

const B64URL_ALPHABET =
  "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_";

const B64URL_LOOKUP: Record<string, number> = (() => {
  const map: Record<string, number> = {};
  for (let i = 0; i < B64URL_ALPHABET.length; i += 1) {
    map[B64URL_ALPHABET[i]] = i;
  }
  // Tolerate standard base64 too: the server sends base64url, but a `+`/`/`
  // key from any other producer should still import rather than throw.
  map["+"] = 62;
  map["/"] = 63;
  return map;
})();

/** Raw bytes. Pinned to `ArrayBuffer` rather than the default
 *  `ArrayBufferLike`, because `BufferSource` — what `crypto.subtle` takes —
 *  excludes a possibly-shared buffer. */
export type Bytes = Uint8Array<ArrayBuffer>;

const HEX_DIGITS = "0123456789abcdef";

export function bytesToHex(bytes: Uint8Array): string {
  let out = "";
  for (let i = 0; i < bytes.length; i += 1) {
    const b = bytes[i];
    out += HEX_DIGITS[b >> 4] + HEX_DIGITS[b & 0x0f];
  }
  return out;
}

const HEX_ONLY_RE = /^[0-9a-fA-F]*$/;

/** Hex → raw bytes. The nonce goes through here before it is ever hashed —
 *  hashing the hex *text* instead is the single most likely way for the two
 *  implementations to disagree, so this is deliberately explicit.
 *
 *  Validation is a whole-string regex rather than a per-byte `parseInt`:
 *  `parseInt` parses PREFIXES, so it quietly accepts `"1z"` as 0x01, `"-1"` as
 *  −1 (which a Uint8Array stores as 0xff) and `" 1"` as 0x01. Every one of those
 *  yields an `H_-1` the server cannot reproduce, with no local signal — the
 *  chain simply fails verification at donation. Throwing is the only honest
 *  outcome for a nonce we cannot decode. */
export function hexToBytes(hex: string): Bytes {
  if (hex.length % 2 !== 0) {
    throw new TrackStoreError("bad_hex", `odd-length hex string (${hex.length})`);
  }
  if (!HEX_ONLY_RE.test(hex)) {
    throw new TrackStoreError("bad_hex", `non-hex characters in ${hex}`);
  }
  const out = new Uint8Array(hex.length / 2);
  for (let i = 0; i < out.length; i += 1) {
    out[i] = Number.parseInt(hex.slice(i * 2, i * 2 + 2), 16);
  }
  return out;
}

export function base64UrlEncode(bytes: Uint8Array): string {
  let out = "";
  for (let i = 0; i < bytes.length; i += 3) {
    const b0 = bytes[i];
    const has1 = i + 1 < bytes.length;
    const has2 = i + 2 < bytes.length;
    const b1 = has1 ? bytes[i + 1] : 0;
    const b2 = has2 ? bytes[i + 2] : 0;
    out += B64URL_ALPHABET[b0 >> 2];
    out += B64URL_ALPHABET[((b0 & 0x03) << 4) | (b1 >> 4)];
    if (!has1) break;
    out += B64URL_ALPHABET[((b1 & 0x0f) << 2) | (b2 >> 6)];
    if (!has2) break;
    out += B64URL_ALPHABET[b2 & 0x3f];
  }
  return out;
}

export function base64UrlDecode(text: string): Bytes {
  const clean = text.replace(/=+$/, "");
  const out = new Uint8Array(Math.floor((clean.length * 6) / 8));
  let acc = 0;
  let bits = 0;
  let o = 0;
  for (const ch of clean) {
    const v = B64URL_LOOKUP[ch];
    if (v === undefined) {
      throw new TrackStoreError(
        "bad_base64url",
        `invalid base64url character ${JSON.stringify(ch)}`,
      );
    }
    acc = (acc << 6) | v;
    bits += 6;
    if (bits >= 8) {
      bits -= 8;
      out[o] = (acc >> bits) & 0xff;
      o += 1;
    }
  }
  return out;
}

const TEXT_ENCODER = new TextEncoder();

/** The compact JWS is ASCII by construction (base64url segments joined by
 *  dots), so UTF-8 encoding it *is* taking its ASCII bytes — Part 2's wording. */
export function asciiBytes(text: string): Bytes {
  return TEXT_ENCODER.encode(text);
}

export function concatBytes(a: Bytes, b: Bytes): Bytes {
  const out = new Uint8Array(a.length + b.length);
  out.set(a, 0);
  out.set(b, a.length);
  return out;
}

export async function sha256(bytes: Bytes): Promise<Bytes> {
  const digest = await crypto.subtle.digest("SHA-256", bytes);
  return new Uint8Array(digest);
}

// ---------------------------------------------------------------------------
// The chain (Part 2): H_-1 = sha256(nonce), H_n = sha256(H_{n-1} || sha256(jws_n))
// ---------------------------------------------------------------------------

/** `H_-1 = sha256(nonce)` — over the nonce's 16 RAW bytes, not its hex text. */
export function initialChainHash(nonceHex: string): Promise<Bytes> {
  return sha256(hexToBytes(nonceHex));
}

/** `sha256(jws_n)` as lowercase hex — this is what a successor batch carries
 *  in `prev`. */
export async function jwsHashHex(jws: string): Promise<string> {
  return bytesToHex(await sha256(asciiBytes(jws)));
}

/** `H_n = sha256(H_{n-1} || sha256(jws_n))`, all raw bytes. */
export async function advanceChainHash(
  previous: Bytes,
  jws: string,
): Promise<Bytes> {
  return sha256(concatBytes(previous, await sha256(asciiBytes(jws))));
}

/** Fold a whole chain to its `chain_root_hash`. The mirror of the server's
 *  check 2 recomputation, and what the golden-vector tests compare against. */
export async function recomputeChainRoot(
  nonceHex: string,
  jwsList: readonly string[],
): Promise<string> {
  let h = await initialChainHash(nonceHex);
  for (const jws of jwsList) h = await advanceChainHash(h, jws);
  return bytesToHex(h);
}

