// Local custody of ride tracks: waypoints recorded on the rider's own device
// as sealed, HMAC-signed, hash-chained batches in IndexedDB. Nothing here
// touches the network and nothing here touches the DOM — the server sees no
// waypoint until the rider explicitly donates the chain at Screen 10.
//
// The wire format is normative and lives in `docs/RIDE_MODE_OVERHAUL_PLAN.md`
// Part 2, which is committed byte-identically to the API repo. Its byte-encoding
// rules are the whole ballgame, because the API's `src/track_verify.py` must
// hash exactly the same bytes:
//
//   * every sha256 input and intermediate value is RAW BYTES, never hex text;
//   * the nonce is HEX-DECODED to its 16 raw bytes before hashing;
//   * `sha256(jws_n)` is taken over the ASCII bytes of the compact JWS string;
//   * `prev` and `chain_root_hash` serialize as LOWERCASE HEX of the digest.
//
// Golden vectors proving this implementation agrees with the API's verifier
// live at `tests/fixtures/track-chain-vectors.json` — one file, the same
// literal path in both repos, regenerated by `scripts/gen-track-vectors.mjs`.
// If you change anything about sealing, signing or chaining, that fixture is
// the contract you are renegotiating with the API repo.

import type { DonateTrackIn, TrackSigning } from "./api.ts";

