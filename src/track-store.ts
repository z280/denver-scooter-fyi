/** `[dt_ms, lat, lon, acc_m]` — `dt_ms` relative to the batch's `t0`. */
export type WaypointTuple = [number, number, number, number];

export interface TrackJwsHeader {
  alg: typeof TRACK_JWS_ALG;
  typ: typeof TRACK_JWS_TYP;
  /** The ride id (`PRIVATE_RIDE_ID` for a private ride). */
  kid: string;
}

export interface TrackBatchPayload {
  v: typeof TRACK_PAYLOAD_VERSION;
  rid: string;
  non: string;
  seq: number;
  /** Lowercase hex sha256 of the predecessor's compact JWS; `""` at seq 0. */
  prev: string;
  t0: number;
  t1: number;
  pts: WaypointTuple[];
  /** True when the batch was sealed from crash-recovered unsealed points. */
  rec: boolean;
}

// Both JSON objects are built with their keys in the exact order Part 2 lists
// them, and JSON.stringify preserves insertion order for non-index keys — that
// is what makes the compact JWS byte-reproducible across runs and across the
// independent generator in scripts/gen-track-vectors.mjs.
function headerJson(kid: string): string {
  const header: TrackJwsHeader = {
    alg: TRACK_JWS_ALG,
    typ: TRACK_JWS_TYP,
    kid,
  };
  return JSON.stringify(header);
}

function payloadJson(payload: TrackBatchPayload): string {
  return JSON.stringify({
    v: payload.v,
    rid: payload.rid,
    non: payload.non,
    seq: payload.seq,
    prev: payload.prev,
    t0: payload.t0,
    t1: payload.t1,
    pts: payload.pts,
    rec: payload.rec,
  });
}

/** Seal one batch into a compact JWS (`header.payload.mac`, HS256). */
export async function signTrackBatch(
  key: CryptoKey,
  kid: string,
  payload: TrackBatchPayload,
): Promise<string> {
  const signingInput = `${base64UrlEncode(
    asciiBytes(headerJson(kid)),
  )}.${base64UrlEncode(asciiBytes(payloadJson(payload)))}`;
  const mac = await crypto.subtle.sign("HMAC", key, asciiBytes(signingInput));
  return `${signingInput}.${base64UrlEncode(new Uint8Array(mac))}`;
}

/** Decode a compact JWS's payload without verifying it. Local reads only —
 *  the client is the key holder, so this proves nothing; the server verifies. */
export function decodeTrackBatch(jws: string): TrackBatchPayload {
  const parts = jws.split(".");
  if (parts.length !== 3) {
    throw new TrackStoreError("bad_jws", `expected 3 JWS segments, got ${parts.length}`);
  }
  const text = new TextDecoder().decode(base64UrlDecode(parts[1]));
  return JSON.parse(text) as TrackBatchPayload;
}

const HMAC_PARAMS: HmacImportParams = { name: "HMAC", hash: "SHA-256" };

/** Import the server-issued per-ride key. `extractable: false` is hygiene, not
 *  a security boundary — for a server ride the raw key is re-fetchable from
 *  `GET /tracked-rides/active`.`track_signing` anyway; it just keeps raw key
 *  bytes out of JS reach at rest. */
export function importTrackKey(keyB64Url: string): Promise<CryptoKey> {
  return crypto.subtle.importKey(
    "raw",
    base64UrlDecode(keyB64Url),
    HMAC_PARAMS,
    false,
    ["sign"],
  );
}

/** Client-random key for a private / guest ride: tamper-evident only, never
 *  points-eligible, never uploaded. */
export function generateTrackKey(): Promise<CryptoKey> {
  return crypto.subtle.generateKey(
    { name: "HMAC", hash: "SHA-256", length: 256 },
    false,
    ["sign"],
  ) as Promise<CryptoKey>;
}

